-- One-time Snowflake setup. Replace the two angle-bracket placeholders.
-- ACCOUNTADMIN is used only for provisioning; the pipeline runs as DEV_ECOSYSTEM_ROLE.

USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS DEV_ECOSYSTEM_ROLE;
CREATE WAREHOUSE IF NOT EXISTS DEV_ECOSYSTEM_WH
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;
CREATE DATABASE IF NOT EXISTS DEV_ECOSYSTEM;
CREATE SCHEMA IF NOT EXISTS DEV_ECOSYSTEM.RAW;
CREATE SCHEMA IF NOT EXISTS DEV_ECOSYSTEM.ANALYTICS;

GRANT USAGE ON WAREHOUSE DEV_ECOSYSTEM_WH TO ROLE DEV_ECOSYSTEM_ROLE;
GRANT USAGE ON DATABASE DEV_ECOSYSTEM TO ROLE DEV_ECOSYSTEM_ROLE;
GRANT USAGE, CREATE TABLE, CREATE VIEW, CREATE STAGE ON SCHEMA DEV_ECOSYSTEM.RAW TO ROLE DEV_ECOSYSTEM_ROLE;
GRANT USAGE, CREATE TABLE, CREATE VIEW ON SCHEMA DEV_ECOSYSTEM.ANALYTICS TO ROLE DEV_ECOSYSTEM_ROLE;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA DEV_ECOSYSTEM.RAW TO ROLE DEV_ECOSYSTEM_ROLE;
GRANT SELECT, INSERT, UPDATE, DELETE ON FUTURE TABLES IN SCHEMA DEV_ECOSYSTEM.RAW TO ROLE DEV_ECOSYSTEM_ROLE;

CREATE STORAGE INTEGRATION IF NOT EXISTS DEV_ECOSYSTEM_S3_INT
  TYPE = EXTERNAL_STAGE
  STORAGE_PROVIDER = S3
  ENABLED = TRUE
  STORAGE_AWS_ROLE_ARN = '<AWS_IAM_ROLE_ARN>'
  STORAGE_ALLOWED_LOCATIONS = ('s3://<BUCKET_NAME>/raw/');

-- Run DESC INTEGRATION DEV_ECOSYSTEM_S3_INT, then add the returned
-- STORAGE_AWS_IAM_USER_ARN and STORAGE_AWS_EXTERNAL_ID to the AWS role trust policy.
DESC INTEGRATION DEV_ECOSYSTEM_S3_INT;

GRANT USAGE ON INTEGRATION DEV_ECOSYSTEM_S3_INT TO ROLE DEV_ECOSYSTEM_ROLE;
GRANT ROLE DEV_ECOSYSTEM_ROLE TO USER <SNOWFLAKE_USER>;
